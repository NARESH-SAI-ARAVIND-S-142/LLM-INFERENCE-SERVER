"""
Tests for the ContinuousBatchScheduler.

Tests scheduler admission, queue overflow, timeout watchdog,
and verifies new Prometheus metrics are registered.
"""

import pytest
import asyncio
import time
from dataclasses import dataclass

import sys
import os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from server.continuous_batch_scheduler import ContinuousBatchScheduler, QueueFullError
from server.sequence import Sequence


@dataclass
class MockRequest:
    """Mimics the request object passed by main.py."""
    prompt: str = None
    messages: list = None
    stream: bool = False
    max_tokens: int = 10
    temperature: float = 1.0
    request_id: str = None


class MockInferenceEngine:
    """
    Fake engine that increments tokens_generated by 1 each step.
    Finishes a sequence when tokens_generated >= max_tokens.
    """
    def _generate_batch_step(self, sequences):
        for seq in sequences:
            if seq.past_key_values is None:
                seq.past_key_values = "mock_pkv"
                seq.input_ids = [1, 2, 3]
                seq.attention_mask = [1, 1, 1]
            else:
                seq.input_ids.append(4)
                seq.attention_mask.append(1)

            seq.tokens_generated += 1
            seq.generated_text += " token"
            if seq.tokens_generated >= seq.max_tokens:
                seq.is_finished = True


